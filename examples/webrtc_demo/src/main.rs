async fn index() -> Html<&'static str> {
    Html(include_str!("../static/index.html"))
}

async fn signal_route(
    headers: HeaderMap,
    upgrade: WebSocketUpgrade,
) -> Result<impl IntoResponse, StatusCode> {
    if headers
        .get(axum::http::header::ORIGIN)
        .and_then(|origin| origin.to_str().ok())
        .is_some_and(|origin| {
            origin != "http://127.0.0.1:8787" && origin != "http://localhost:8787"
        })
    {
        return Err(StatusCode::FORBIDDEN);
    }
    Ok(upgrade
        .max_message_size(1024 * 1024)
        .max_frame_size(1024 * 1024)
        .on_upgrade(run_session))
}

async fn run_session(socket: WebSocket) {
    if let Err(error) = run_session_inner(socket).await {
        eprintln!("WebRTC demo session ended: {error}");
    }
}

async fn run_session_inner(socket: WebSocket) -> anyhow::Result<()> {
    let factory = PeerConnectionFactory::builder().build()?;
    let session = Arc::new(GshSession::new_with_video_codecs(
        factory,
        RtcConfiguration::default(),
        SessionRole::Offerer,
        WIDTH,
        HEIGHT,
        &[VideoCodec::Vp8],
    )?);

    let offer = session.create_offer()?;
    if session.negotiated_video_codec().is_some() {
        anyhow::bail!("negotiated codec is unexpectedly available before SDP answer");
    }

    let (mut socket_tx, mut socket_rx) = socket.split();
    let (signal_tx, mut signal_rx) = mpsc::channel::<Message>(SIGNAL_QUEUE_CAPACITY);
    tokio::spawn(async move {
        while let Some(message) = signal_rx.recv().await {
            if socket_tx.send(message).await.is_err() {
                break;
            }
        }
    });

    send_signal(&signal_tx, json!({ "type": "offer", "sdp": offer.sdp })).await?;
    send_signal(
        &signal_tx,
        json!({ "type": "status", "message": "Offer sent; waiting for browser answer" }),
    )
    .await?;

    let mut remote_description_set = false;
    let mut pending_candidates = VecDeque::new();
    let mut pacer = FramePacer::new(30)?;
    let mut frame_number = 0_u32;
    let mut input_count = 0_u64;

    loop {
        tokio::select! {
            incoming = socket_rx.next() => {
                let Some(incoming) = incoming else { break; };
                match incoming? {
                    Message::Text(text) => {
                        let value: Value = serde_json::from_str(text.as_str())?;
                        match value.get("type").and_then(Value::as_str) {
                            Some("answer") => {
                                if remote_description_set {
                                    anyhow::bail!("duplicate remote answer");
                                }
                                let sdp = value.get("sdp").and_then(Value::as_str)
                                    .ok_or_else(|| anyhow::anyhow!("answer has no SDP string"))?;
                                session.accept_answer(libgsh::webrtc::SdpMessage {
                                    kind: libgsh::webrtc::DescriptionKind::Answer,
                                    sdp: sdp.to_owned(),
                                })?;
                                remote_description_set = true;
                                while let Some(candidate) = pending_candidates.pop_front() {
                                    session.add_ice_candidate(candidate)?;
                                }
                                send_signal(&signal_tx, json!({
                                    "type": "status",
                                    "message": format!("Connected codec: {:?}", session.negotiated_video_codec())
                                })).await?;
                            }
                            Some("candidate") => {
                                let candidate = parse_candidate(&value)?;
                                if remote_description_set {
                                    session.add_ice_candidate(candidate)?;
                                } else {
                                    if pending_candidates.len() == ICE_QUEUE_LIMIT {
                                        anyhow::bail!("too many candidates before remote SDP");
                                    }
                                    pending_candidates.push_back(candidate);
                                }
                            }
                            other => anyhow::bail!("unexpected signaling message type: {other:?}"),
                        }
                    }
                    Message::Ping(payload) => {
                        signal_tx.send(Message::Pong(payload)).await?;
                    }
                    Message::Close(_) => break,
                    Message::Binary(_) | Message::Pong(_) => {}
                }
            }
            candidate = session.next_ice_candidate() => {
                if let Some(candidate) = candidate? {
                    send_signal(&signal_tx, json!({
                        "type": "candidate",
                        "candidate": {
                            "candidate": candidate.candidate,
                            "sdpMid": candidate.sdp_mid,
                            "sdpMLineIndex": candidate.sdp_mline_index
                        }
                    })).await?;
                }
            }
            input = session.recv_input() => {
                let input: UserInput = input?;
                input_count += 1;
                if input_count == 1 {
                    send_signal(&signal_tx, json!({
                        "type": "status",
                        "message": "First browser input reached the GSH session"
                    })).await?;
                }
                if input_count.is_power_of_two() {
                    eprintln!("received input #{input_count}: {input:?}");
                }
            }
            feedback = session.recv_encoder_feedback() => {
                match feedback? {
                    libgsh::webrtc::VideoEncoderFeedback::RequestKeyFrame => {
                        // The demo sends a keyframe for every frame.
                        eprintln!("encoder feedback: keyframe requested (already satisfied)");
                    }
                    libgsh::webrtc::VideoEncoderFeedback::RateUpdate {
                        bitrate_bps,
                        framerate_fps,
                    } => {
                        eprintln!("encoder feedback: {bitrate_bps} bps @ {framerate_fps:.1} fps");
                    }
                }
            }
            tick = pacer.wait_next() => {
                if session.negotiated_video_codec() == Some(VideoCodec::Vp8) {
                    let result = session.send_video(EncodedVideoFrame {
                        data: VP8_KEYFRAME.to_vec(),
                        codec: VideoCodec::Vp8,
                        is_key_frame: true,
                        width: WIDTH,
                        height: HEIGHT,
                        rtp_timestamp: frame_number.wrapping_mul(3_000),
                    });
                    if let Err(error) = result {
                        if error.frame.is_none() {
                            anyhow::bail!("video session failed: {}", error.error);
                        }
                    }
                    frame_number = frame_number.wrapping_add(1);
                }
                if tick.skipped > 0 {
                    eprintln!("frame pacer skipped {} deadline(s)", tick.skipped);
                }
            }
        }
    }

    Ok(())
}

const ICE_QUEUE_LIMIT: usize = 256;

async fn send_signal(sender: &mpsc::Sender<Message>, value: Value) -> anyhow::Result<()> {
    sender.send(Message::Text(value.to_string().into())).await?;
    Ok(())
}

fn parse_candidate(value: &Value) -> anyhow::Result<CandidateMessage> {
    let candidate = value
        .get("candidate")
        .filter(|value| value.is_object())
        .unwrap_or(value);
    Ok(CandidateMessage {
        candidate: candidate
            .get("candidate")
            .and_then(Value::as_str)
            .ok_or_else(|| anyhow::anyhow!("candidate payload has no candidate string"))?
            .to_owned(),
        sdp_mid: candidate
            .get("sdpMid")
            .and_then(Value::as_str)
            .map(str::to_owned),
        sdp_mline_index: candidate
            .get("sdpMLineIndex")
            .and_then(Value::as_u64)
            .and_then(|value| u16::try_from(value).ok()),
    })
}

#[tokio::main]
async fn main() -> anyhow::Result<()> {
    let address = SocketAddr::from(([127, 0, 0, 1], 8787));
    let app = Router::new()
        .route("/", get(index))
        .route("/signal", get(signal_route));
    let listener = TcpListener::bind(address).await?;
    eprintln!("Local-only GSH WebRTC demo: http://{address}/");
    eprintln!("Signaling is unauthenticated and plain WS; keep it on loopback.");
    axum::serve(listener, app).await?;
    Ok(())
}
